import androidx.sqlite.db.SupportSQLiteDatabase
import com.habittracker.data.local.entity.PensionLotteryDrawEntity

object PensionLotterySeedData {
    val draws: List<PensionLotteryDrawEntity> by lazy {
        encodedDraws.lineSequence()
            .filter(String::isNotBlank)
            .map { line ->
                val values = line.split(',')
                PensionLotteryDrawEntity(
                    roundNo = values[0].toInt(),
                    groupNo = values[1].toInt(),
                    winningNumber = values[2],
                )
            }
            .toList()
    }

    fun insertInto(database: SupportSQLiteDatabase) {
        database.compileStatement(
            "INSERT OR IGNORE INTO pension_lottery_draw (round_no, group_no, winning_number) VALUES (?, ?, ?)",
        ).use { statement ->
            draws.forEach { draw ->
                statement.clearBindings()
                statement.bindLong(1, draw.roundNo.toLong())
                statement.bindLong(2, draw.groupNo.toLong())
                statement.bindString(3, draw.winningNumber)
                statement.executeInsert()
            }
        }
    }

